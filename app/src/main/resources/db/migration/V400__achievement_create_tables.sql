-- Пакет achievement: единый реестр достижений и маршрут согласования (ФР-03, ФР-04, ФР-05, разделы 4 и 5).
-- Достижение вносится один раз и связывается со всеми авторами, включая внешних.
-- Показатель, редакция, период и пользователи живут в других пакетах, поэтому внешних
-- ключей на них нет: существование проверяет сервис.

CREATE TABLE ach_achievement (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_id         BIGINT        NOT NULL,
    indicator_version_id BIGINT        NOT NULL,
    period_id            BIGINT        NOT NULL,
    achievement_type     VARCHAR(30)   NOT NULL,
    owner_id             BIGINT        NOT NULL,
    entered_by           BIGINT,
    basis                VARCHAR(1000),
    title                VARCHAR(500)  NOT NULL,
    title_norm           VARCHAR(500)  NOT NULL,
    event_date           DATE          NOT NULL,
    identifier_type      VARCHAR(20),
    identifier           VARCHAR(500),
    identifier_norm      VARCHAR(500),
    program_id           BIGINT,
    discipline           VARCHAR(255),
    description          VARCHAR(2000),
    quantity             NUMERIC(12,2),
    status               VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    reviewer_kind        VARCHAR(10)   NOT NULL DEFAULT 'ROP',
    possible_duplicate   BOOLEAN       NOT NULL DEFAULT FALSE,
    last_comment         VARCHAR(1000),
    revision             INTEGER       NOT NULL DEFAULT 1,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ach_achievement_type_ck CHECK (achievement_type IN ('PUBLICATION', 'UMK_DOCUMENT', 'EVENT', 'CONTRACT', 'CONFERENCE', 'OTHER')),
    CONSTRAINT ach_achievement_identifier_type_ck CHECK (identifier_type IN ('DOI', 'URL', 'DOC_NUMBER')),
    -- идентификатор заполняется целиком: вид, как ввели и нормализованное значение
    CONSTRAINT ach_achievement_identifier_ck CHECK (num_nonnulls(identifier_type, identifier, identifier_norm) IN (0, 3)),
    -- ввод за другого допускается только с фиксацией инициатора и основания (ТЗ 2.2)
    CONSTRAINT ach_achievement_entered_ck CHECK ((entered_by IS NULL) = (basis IS NULL)),
    CONSTRAINT ach_achievement_quantity_ck CHECK (quantity > 0),
    CONSTRAINT ach_achievement_status_ck CHECK (status IN ('DRAFT', 'ON_REVIEW', 'RETURNED', 'REVIEWED', 'APPROVED', 'REJECTED', 'REVISION')),
    CONSTRAINT ach_achievement_reviewer_ck CHECK (reviewer_kind IN ('ROP', 'DIRECTOR')),
    -- возврат, отклонение и пересмотр всегда с причиной
    CONSTRAINT ach_achievement_comment_ck CHECK (status NOT IN ('RETURNED', 'REJECTED', 'REVISION') OR last_comment IS NOT NULL),
    CONSTRAINT ach_achievement_revision_ck CHECK (revision > 0)
);

-- Строгий ключ дублей (ТЗ 5.2): вид достижения + DOI или номер документа.
-- URL в ключ не входит: один адрес не обязательно означает одно достижение.
-- Отклонённая запись не мешает внести достижение заново.
CREATE UNIQUE INDEX ach_achievement_identifier_uk ON ach_achievement (achievement_type, identifier_type, identifier_norm)
    WHERE identifier_type IN ('DOI', 'DOC_NUMBER') AND status <> 'REJECTED';
-- свои достижения и личные итоги
CREATE INDEX ach_achievement_owner_period_idx ON ach_achievement (owner_id, period_id);
-- очереди РОП и директора, состояние согласования
CREATE INDEX ach_achievement_period_status_idx ON ach_achievement (period_id, status);
CREATE INDEX ach_achievement_status_program_idx ON ach_achievement (status, program_id);
-- поиск похожих записей, когда строгого идентификатора нет
CREATE INDEX ach_achievement_title_norm_idx ON ach_achievement (title_norm);
CREATE INDEX ach_achievement_indicator_date_idx ON ach_achievement (indicator_id, event_date);

COMMENT ON TABLE ach_achievement IS 'Единый реестр достижений. Удалить можно только черновик';
COMMENT ON COLUMN ach_achievement.indicator_version_id IS 'Редакция показателя, по которой считается достижение';
COMMENT ON COLUMN ach_achievement.achievement_type IS 'Копия вида из редакции показателя: нужна для уникального индекса';
COMMENT ON COLUMN ach_achievement.owner_id IS 'Заявитель; он же первый участник';
COMMENT ON COLUMN ach_achievement.reviewer_kind IS 'ROP — проверяет РОП программы; DIRECTOR — заявитель сам РОП, проверку и утверждение выполняет директор отдельными решениями';
COMMENT ON COLUMN ach_achievement.possible_duplicate IS 'При отправке нашлись похожие записи: РОП решает с обязательным обоснованием (ТЗ 5.2 п. 4)';
COMMENT ON COLUMN ach_achievement.revision IS 'Редакция данных и расчёта, растёт при пересмотре и присоединении соавтора';

-- Участники и их доли (ТЗ 6.1, 11.1). Доля внешнего автора остаётся у него и никому не перераспределяется.
CREATE TABLE ach_participant (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT        NOT NULL,
    user_id        BIGINT,
    external_name  VARCHAR(300),
    weight         NUMERIC(10,4) NOT NULL DEFAULT 1,
    share          NUMERIC(9,6)  NOT NULL,
    points_exact   NUMERIC(14,6) NOT NULL,
    points         NUMERIC(12,2) NOT NULL,
    basis          VARCHAR(1000),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ach_participant_achievement_fk FOREIGN KEY (achievement_id) REFERENCES ach_achievement (id) ON DELETE CASCADE,
    -- участник — либо сотрудник, либо внешний автор
    CONSTRAINT ach_participant_person_ck CHECK (num_nonnulls(user_id, external_name) = 1),
    CONSTRAINT ach_participant_weight_ck CHECK (weight > 0),
    CONSTRAINT ach_participant_share_ck CHECK (share > 0 AND share <= 1),
    CONSTRAINT ach_participant_points_ck CHECK (points >= 0 AND points_exact >= 0)
);

CREATE UNIQUE INDEX ach_participant_user_uk ON ach_participant (achievement_id, user_id) WHERE user_id IS NOT NULL;
CREATE INDEX ach_participant_achievement_idx ON ach_participant (achievement_id);
CREATE INDEX ach_participant_user_idx ON ach_participant (user_id);

COMMENT ON TABLE ach_participant IS 'Авторы достижения. Лишний цент при равных остатках достаётся участнику с меньшим id';
COMMENT ON COLUMN ach_participant.share IS 'Доля α = w / Σw';
COMMENT ON COLUMN ach_participant.points_exact IS 'B × c × α без округления до копеек, не меньше четырёх знаков';
COMMENT ON COLUMN ach_participant.points IS 'Официальный балл, два знака, распределён методом наибольших остатков';

-- Подтверждения: файл или ссылка (ФР-04). Новая версия документа ссылается на предыдущую.
CREATE TABLE ach_evidence (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id  BIGINT        NOT NULL,
    doc_type        VARCHAR(100)  NOT NULL,
    requisites      VARCHAR(500),
    original_name   VARCHAR(255),
    content_type    VARCHAR(100),
    size_bytes      BIGINT,
    storage_key     VARCHAR(100),
    checksum_sha256 VARCHAR(64),
    url             VARCHAR(1000),
    version_no      INTEGER       NOT NULL DEFAULT 1,
    previous_id     BIGINT,
    scan_status     VARCHAR(20)   NOT NULL DEFAULT 'NOT_SCANNED',
    archived_at     TIMESTAMPTZ,
    uploaded_by     BIGINT        NOT NULL,
    uploaded_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ach_evidence_achievement_fk FOREIGN KEY (achievement_id) REFERENCES ach_achievement (id) ON DELETE CASCADE,
    CONSTRAINT ach_evidence_previous_fk FOREIGN KEY (previous_id) REFERENCES ach_evidence (id),
    CONSTRAINT ach_evidence_storage_key_uk UNIQUE (storage_key),
    -- либо ссылка, либо файл со всеми его сведениями
    CONSTRAINT ach_evidence_source_ck CHECK (
        (url IS NOT NULL AND num_nonnulls(original_name, content_type, size_bytes, storage_key, checksum_sha256) = 0)
        OR (url IS NULL AND num_nonnulls(original_name, content_type, size_bytes, storage_key, checksum_sha256) = 5)
    ),
    CONSTRAINT ach_evidence_size_ck CHECK (size_bytes > 0),
    CONSTRAINT ach_evidence_checksum_ck CHECK (char_length(checksum_sha256) = 64),
    CONSTRAINT ach_evidence_version_ck CHECK (version_no > 0),
    CONSTRAINT ach_evidence_scan_ck CHECK (scan_status IN ('NOT_SCANNED', 'CLEAN', 'INFECTED'))
);

CREATE INDEX ach_evidence_achievement_idx ON ach_evidence (achievement_id);

COMMENT ON TABLE ach_evidence IS 'Подтверждающие документы. Допустимые форматы и размер задаются настройками приложения, а не схемой (ФР-04)';
COMMENT ON COLUMN ach_evidence.storage_key IS 'Имя файла на диске (UUID), а не имя от пользователя';
COMMENT ON COLUMN ach_evidence.archived_at IS 'Документ снят с достижения. У достижения с утверждёнными начислениями документы не удаляются';

-- Решения на маршруте (ТЗ 11.1, Approval / Decision). Строки только добавляются.
CREATE TABLE ach_decision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT        NOT NULL,
    revision       INTEGER       NOT NULL,
    action         VARCHAR(20)   NOT NULL,
    actor_id       BIGINT        NOT NULL,
    comment        VARCHAR(1000),
    decided_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ach_decision_achievement_fk FOREIGN KEY (achievement_id) REFERENCES ach_achievement (id) ON DELETE CASCADE,
    CONSTRAINT ach_decision_action_ck CHECK (action IN ('CREATED', 'SUBMITTED', 'RETURNED', 'REVIEWED', 'APPROVED', 'REJECTED', 'JOINED', 'REVISION')),
    CONSTRAINT ach_decision_comment_ck CHECK (action NOT IN ('RETURNED', 'REJECTED', 'REVISION') OR comment IS NOT NULL)
);

CREATE INDEX ach_decision_achievement_idx ON ach_decision (achievement_id, decided_at);

COMMENT ON TABLE ach_decision IS 'Кто, когда и какое решение принял, с какой редакцией данных';

-- Прежние редакции достижения (ФР-06): перед пересмотром или присоединением соавтора
-- сюда сохраняются карточка, участники и документы. Строки только добавляются.
CREATE TABLE ach_achievement_revision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id BIGINT      NOT NULL,
    revision       INTEGER     NOT NULL,
    data           JSONB       NOT NULL,
    created_by     BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ach_achievement_revision_achievement_fk FOREIGN KEY (achievement_id) REFERENCES ach_achievement (id) ON DELETE CASCADE,
    CONSTRAINT ach_achievement_revision_uk UNIQUE (achievement_id, revision),
    CONSTRAINT ach_achievement_revision_data_ck CHECK (jsonb_typeof(data) = 'object')
);

COMMENT ON TABLE ach_achievement_revision IS 'Снимки прежних редакций достижения. Прямая правка утверждённой записи запрещена';
