-- Пакет indicator: справочник показателей и их редакции (ТЗ 1.3 п. 4, ФР-02, 11.1).
-- Показатель — постоянный код и категория. Всё, что влияет на расчёт, лежит в редакции.
-- Редакция после создания не меняется: правка показателя создаёт новую редакцию,
-- а утверждённые результаты ссылаются на ту, по которой были посчитаны.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE ind_indicator (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20) NOT NULL,
    category    VARCHAR(10) NOT NULL,
    archived    BOOLEAN     NOT NULL DEFAULT FALSE,
    archived_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ind_indicator_code_uk UNIQUE (code),
    CONSTRAINT ind_indicator_category_ck CHECK (category IN ('PPS', 'AUP', 'ROP')),
    CONSTRAINT ind_indicator_archived_ck CHECK (archived = (archived_at IS NOT NULL))
);

COMMENT ON TABLE ind_indicator IS 'Показатели: ППС-01, АУП-04, РОП-11. Не удаляются, а переносятся в архив';

CREATE TABLE ind_indicator_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_id      BIGINT        NOT NULL,
    version_no        INTEGER       NOT NULL,
    name              VARCHAR(500)  NOT NULL,
    methodology       VARCHAR(2000),
    evaluation_type   VARCHAR(10)   NOT NULL,
    unit              VARCHAR(30)   NOT NULL,
    achievement_type  VARCHAR(30),
    base_points       NUMERIC(10,4),
    accrual_method    VARCHAR(15),
    target_value      NUMERIC(14,4),
    direction         VARCHAR(10),
    percent           BOOLEAN       NOT NULL DEFAULT FALSE,
    coefficient       NUMERIC(10,4) NOT NULL DEFAULT 1,
    max_points        NUMERIC(12,2),
    max_repeats       INTEGER,
    required          BOOLEAN       NOT NULL DEFAULT FALSE,
    requires_program  BOOLEAN       NOT NULL DEFAULT FALSE,
    evidence          VARCHAR(1000) NOT NULL,
    evidence_required BOOLEAN       NOT NULL DEFAULT TRUE,
    valid_from        DATE          NOT NULL,
    valid_to          DATE,
    created_by        BIGINT,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ind_indicator_version_indicator_fk FOREIGN KEY (indicator_id) REFERENCES ind_indicator (id),
    CONSTRAINT ind_indicator_version_no_uk UNIQUE (indicator_id, version_no),
    CONSTRAINT ind_indicator_version_no_ck CHECK (version_no > 0),
    CONSTRAINT ind_indicator_version_type_ck CHECK (evaluation_type IN ('POINTS', 'TARGET')),
    CONSTRAINT ind_indicator_version_achievement_type_ck CHECK (achievement_type IN ('PUBLICATION', 'UMK_DOCUMENT', 'EVENT', 'CONTRACT', 'CONFERENCE', 'OTHER')),
    CONSTRAINT ind_indicator_version_accrual_ck CHECK (accrual_method IN ('INDIVIDUAL', 'SHARED')),
    CONSTRAINT ind_indicator_version_direction_ck CHECK (direction IN ('AT_LEAST', 'AT_MOST')),
    -- балльный показатель и целевой — самостоятельные типы оценки (ТЗ 1.3 п. 5): поля одного не заполняются у другого
    CONSTRAINT ind_indicator_version_fields_ck CHECK (
        (evaluation_type = 'POINTS'
            AND base_points IS NOT NULL AND accrual_method IS NOT NULL AND achievement_type IS NOT NULL
            AND target_value IS NULL AND direction IS NULL AND NOT percent)
        OR
        (evaluation_type = 'TARGET'
            AND target_value IS NOT NULL AND direction IS NOT NULL
            AND base_points IS NULL AND accrual_method IS NULL AND achievement_type IS NULL)
    ),
    CONSTRAINT ind_indicator_version_base_points_ck CHECK (base_points > 0),
    CONSTRAINT ind_indicator_version_coefficient_ck CHECK (coefficient > 0),
    CONSTRAINT ind_indicator_version_max_points_ck CHECK (max_points > 0),
    CONSTRAINT ind_indicator_version_max_repeats_ck CHECK (max_repeats > 0),
    CONSTRAINT ind_indicator_version_dates_ck CHECK (valid_to IS NULL OR valid_to >= valid_from),
    -- на любую дату у показателя действует одна редакция
    CONSTRAINT ind_indicator_version_no_overlap_ex EXCLUDE USING gist (
        indicator_id WITH =,
        daterange(valid_from, valid_to, '[]') WITH &&
    )
);

COMMENT ON TABLE ind_indicator_version IS 'Редакции показателя. К отчётному периоду относится редакция, действующая на дату начала периода';
COMMENT ON COLUMN ind_indicator_version.achievement_type IS 'Вид достижения: входит в строгий ключ дублей. Задан в редакции, чтобы дубль нельзя было обойти выбором другого вида';
COMMENT ON COLUMN ind_indicator_version.base_points IS 'Базовый балл B за одно достижение';
COMMENT ON COLUMN ind_indicator_version.accrual_method IS 'INDIVIDUAL — автору целиком; SHARED — B делится между всеми авторами, включая внешних';
COMMENT ON COLUMN ind_indicator_version.coefficient IS 'Коэффициент c, по умолчанию 1 (ТЗ 6.2)';
COMMENT ON COLUMN ind_indicator_version.max_points IS 'Максимум M за период; NULL — без ограничения';
COMMENT ON COLUMN ind_indicator_version.max_repeats IS 'Сколько раз за период можно начислить; NULL — без ограничения';
COMMENT ON COLUMN ind_indicator_version.percent IS 'Факт считается как процент: 100 × числитель / знаменатель';
COMMENT ON COLUMN ind_indicator_version.evidence IS 'Перечень подтверждающих документов из «Порядка начисления баллов»';
