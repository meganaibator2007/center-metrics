-- Пакет indicator: категории и показатели.
-- Правило расчёта баллов хранится в самом показателе: способ, коэффициент, максимум.

CREATE TABLE ind_category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ind_category_name_uk UNIQUE (name)
);

COMMENT ON TABLE ind_category IS 'Категории (разделы) показателей: учебная, научная, методическая работа и т. д.';

CREATE TABLE ind_indicator (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id         BIGINT        NOT NULL,
    name                VARCHAR(255)  NOT NULL,
    description         VARCHAR(1000),
    unit                VARCHAR(20)   NOT NULL,
    scoring_method      VARCHAR(20)   NOT NULL DEFAULT 'PER_UNIT',
    coefficient         NUMERIC(10,3) NOT NULL,
    max_score           NUMERIC(10,2) NOT NULL,
    required            BOOLEAN       NOT NULL DEFAULT FALSE,
    attachment_required BOOLEAN       NOT NULL DEFAULT FALSE,
    fields              JSONB         NOT NULL DEFAULT '[]',
    sort_order          INTEGER       NOT NULL DEFAULT 0,
    archived            BOOLEAN       NOT NULL DEFAULT FALSE,
    archived_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),

    -- внешний ключ внутри пакета разрешён: категория и показатель — один агрегат
    CONSTRAINT ind_indicator_category_fk FOREIGN KEY (category_id) REFERENCES ind_category (id),
    CONSTRAINT ind_indicator_scoring_method_ck CHECK (scoring_method IN ('PER_UNIT', 'FIXED')),
    CONSTRAINT ind_indicator_coefficient_ck CHECK (coefficient > 0),
    CONSTRAINT ind_indicator_max_score_ck CHECK (max_score > 0),
    CONSTRAINT ind_indicator_fields_ck CHECK (jsonb_typeof(fields) = 'array'),
    CONSTRAINT ind_indicator_archived_ck CHECK (archived = (archived_at IS NOT NULL))
);

CREATE INDEX ind_indicator_category_idx ON ind_indicator (category_id);
-- два действующих показателя с одним названием в одной категории не нужны; архивные не мешают
CREATE UNIQUE INDEX ind_indicator_name_uk ON ind_indicator (category_id, lower(name)) WHERE NOT archived;

COMMENT ON TABLE ind_indicator IS 'Показатели. Не удаляются, а переносятся в архив, чтобы старые отчёты не ломались';
COMMENT ON COLUMN ind_indicator.scoring_method IS 'PER_UNIT: сумма значений × коэффициент; FIXED: число записей × коэффициент. В обоих случаях не больше max_score';
COMMENT ON COLUMN ind_indicator.fields IS 'Поля формы ввода: [{"key","label","type":TEXT|NUMBER|DATE|URL|SELECT,"required","options":[...]}]';
COMMENT ON COLUMN ind_indicator.attachment_required IS 'Без прикреплённого файла по показателю отчёт не отправить';
