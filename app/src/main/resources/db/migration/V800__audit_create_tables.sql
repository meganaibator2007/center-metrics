-- Пакет audit: журнал значимых действий (ТЗ 1.3 п. 6, 11.1, раздел 12).
-- Другие пакеты публикуют событие AuditRecorded из common, этот пакет его записывает.
-- Строки только добавляются.

CREATE TABLE aud_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actor_id    BIGINT,
    actor_name  VARCHAR(300)  NOT NULL,
    action      VARCHAR(50)   NOT NULL,
    object_type VARCHAR(50)   NOT NULL,
    object_id   BIGINT,
    object_name VARCHAR(500)  NOT NULL,
    old_data    JSONB,
    new_data    JSONB,
    comment     VARCHAR(1000)
);

-- журнал по порядку, новые сверху
CREATE INDEX aud_event_occurred_idx ON aud_event (occurred_at DESC);
-- история одного объекта
CREATE INDEX aud_event_object_idx ON aud_event (object_type, object_id);
-- действия одного человека
CREATE INDEX aud_event_actor_idx ON aud_event (actor_id, occurred_at DESC);

COMMENT ON TABLE aud_event IS 'Кто, когда, что изменил, прежняя и новая версия, основание';
COMMENT ON COLUMN aud_event.actor_id IS 'NULL — действие выполнила сама система';
COMMENT ON COLUMN aud_event.actor_name IS 'ФИО на момент действия: журнал не зависит от последующих правок пользователя';
