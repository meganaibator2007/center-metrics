-- Пакет measurement: периодические значения целевых показателей РОП (ФР-03, разделы 5.3, 6.3).
-- Это не достижение: значение законно измеряется каждый период, поэтому новое значение
-- за следующий период дублем не считается, а второе за тот же период — считается.

CREATE TABLE msr_measurement (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_id         BIGINT        NOT NULL,
    indicator_version_id BIGINT        NOT NULL,
    period_id            BIGINT        NOT NULL,
    program_id           BIGINT        NOT NULL,
    revision             INTEGER       NOT NULL DEFAULT 1,
    is_current           BOOLEAN       NOT NULL DEFAULT TRUE,
    value                NUMERIC(14,4),
    numerator            NUMERIC(14,4),
    denominator          NUMERIC(14,4),
    scale                VARCHAR(100),
    source               VARCHAR(500),
    document_basis       VARCHAR(500),
    status               VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    last_comment         VARCHAR(1000),
    entered_by           BIGINT        NOT NULL,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT msr_measurement_revision_uk UNIQUE (indicator_version_id, period_id, program_id, revision),
    CONSTRAINT msr_measurement_revision_ck CHECK (revision > 0),
    CONSTRAINT msr_measurement_status_ck CHECK (status IN ('DRAFT', 'ON_REVIEW', 'RETURNED', 'REVIEWED', 'APPROVED', 'REJECTED', 'REVISION')),
    CONSTRAINT msr_measurement_comment_ck CHECK (status NOT IN ('RETURNED', 'REJECTED', 'REVISION') OR last_comment IS NOT NULL),
    CONSTRAINT msr_measurement_value_ck CHECK (value >= 0),
    CONSTRAINT msr_measurement_fraction_ck CHECK ((numerator IS NULL) = (denominator IS NULL)),
    CONSTRAINT msr_measurement_fraction_range_ck CHECK (numerator >= 0 AND denominator >= 0),
    -- при нулевом знаменателе факта нет: показатель помечается «недостаточно данных»
    CONSTRAINT msr_measurement_no_data_ck CHECK (denominator <> 0 OR value IS NULL),
    -- без числителя и знаменателя факт обязателен
    CONSTRAINT msr_measurement_filled_ck CHECK (numerator IS NOT NULL OR value IS NOT NULL)
);

-- Уникальность измерения (ТЗ 5.3, 11.2): показатель с редакцией + период + программа.
-- Исправления версионируются, поэтому ключ действует только среди текущих значений.
CREATE UNIQUE INDEX msr_measurement_current_uk ON msr_measurement (indicator_version_id, period_id, program_id) WHERE is_current;
-- реестр целей: период и программа, дашборд директора
CREATE INDEX msr_measurement_period_program_idx ON msr_measurement (period_id, program_id);

COMMENT ON TABLE msr_measurement IS 'Измерения целевых показателей. Строка с is_current = false — прежняя версия исправленного значения';
COMMENT ON COLUMN msr_measurement.value IS 'Факт F. Для процентных показателей F = 100 × A / D; NULL при D = 0';
COMMENT ON COLUMN msr_measurement.scale IS 'Применяемая шкала для показателей удовлетворённости';
COMMENT ON COLUMN msr_measurement.source IS 'Источник данных или выборки';
COMMENT ON COLUMN msr_measurement.document_basis IS 'Документ-основание (ТЗ 4.2)';

-- Решения на маршруте измерения: проверка данных и итоговое решение директора фиксируются отдельно (ТЗ 4.2).
CREATE TABLE msr_decision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    measurement_id BIGINT        NOT NULL,
    action         VARCHAR(20)   NOT NULL,
    actor_id       BIGINT        NOT NULL,
    comment        VARCHAR(1000),
    decided_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT msr_decision_measurement_fk FOREIGN KEY (measurement_id) REFERENCES msr_measurement (id) ON DELETE CASCADE,
    CONSTRAINT msr_decision_action_ck CHECK (action IN ('CREATED', 'SUBMITTED', 'RETURNED', 'REVIEWED', 'APPROVED', 'REJECTED', 'REVISION')),
    CONSTRAINT msr_decision_comment_ck CHECK (action NOT IN ('RETURNED', 'REJECTED', 'REVISION') OR comment IS NOT NULL)
);

CREATE INDEX msr_decision_measurement_idx ON msr_decision (measurement_id, decided_at);

COMMENT ON TABLE msr_decision IS 'История решений по измерению. Строки только добавляются';
