-- Пакет importing: загрузка XLSX с предварительной проверкой и протоколом (раздел 7).
-- Файл сначала проверяется и ничего не меняет (VALIDATED), применяется отдельным подтверждением (APPLIED).

CREATE TABLE imp_job (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL,
    file_name   VARCHAR(255) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'VALIDATED',
    uploaded_by BIGINT       NOT NULL,
    uploaded_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    applied_by  BIGINT,
    applied_at  TIMESTAMPTZ,

    CONSTRAINT imp_job_type_ck CHECK (type IN ('EMPLOYEES', 'INDICATORS', 'MEASUREMENTS', 'ACHIEVEMENTS')),
    CONSTRAINT imp_job_status_ck CHECK (status IN ('VALIDATED', 'APPLIED')),
    CONSTRAINT imp_job_applied_ck CHECK ((status = 'APPLIED') = (applied_at IS NOT NULL)),
    CONSTRAINT imp_job_applied_by_ck CHECK ((status = 'APPLIED') = (applied_by IS NOT NULL))
);

CREATE INDEX imp_job_uploaded_idx ON imp_job (uploaded_at DESC);

COMMENT ON TABLE imp_job IS 'Загрузки XLSX: кто, когда, какой набор и применён ли он';

CREATE TABLE imp_row (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id  BIGINT       NOT NULL,
    row_no  INTEGER      NOT NULL,
    action  VARCHAR(10)  NOT NULL,
    key     VARCHAR(255) NOT NULL,
    message VARCHAR(1000),
    payload JSONB,

    CONSTRAINT imp_row_job_fk FOREIGN KEY (job_id) REFERENCES imp_job (id) ON DELETE CASCADE,
    CONSTRAINT imp_row_uk UNIQUE (job_id, row_no),
    CONSTRAINT imp_row_no_ck CHECK (row_no > 0),
    CONSTRAINT imp_row_action_ck CHECK (action IN ('NEW', 'UPDATE', 'SKIP', 'ERROR')),
    CONSTRAINT imp_row_error_ck CHECK (action <> 'ERROR' OR message IS NOT NULL)
);

COMMENT ON TABLE imp_row IS 'Протокол импорта по строкам файла';
COMMENT ON COLUMN imp_row.key IS 'Устойчивый ключ сопоставления: повторная загрузка не создаёт дублей (ТЗ 7.2)';
COMMENT ON COLUMN imp_row.payload IS 'Разобранная строка: что будет применено после подтверждения';
