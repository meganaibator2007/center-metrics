-- Пакет scoring: рассчитанные баллы.
-- Одна строка — итог по показателю у преподавателя за период: по записям журнала,
-- дата которых входит в этот период. Одна запись может считаться в нескольких периодах
-- (октябрь и семестр), у каждого периода свой итог и свой максимум.
-- Пересчитывается в той же транзакции, что и сохранение или удаление записи (событие EntryChanged),
-- для всех открытых периодов, в которые попадает дата записи (старая и новая, если дату поменяли).
-- Коэффициент, максимум и способ расчёта копируются в строку в момент расчёта:
-- если админ потом изменит показатель, баллы закрытого периода останутся прежними и объяснимыми.

CREATE TABLE scr_score (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     BIGINT        NOT NULL,
    period_id      BIGINT        NOT NULL,
    indicator_id   BIGINT        NOT NULL,
    entry_count    INTEGER       NOT NULL,
    total_value    NUMERIC(14,2) NOT NULL,
    scoring_method VARCHAR(20)   NOT NULL,
    coefficient    NUMERIC(10,3) NOT NULL,
    max_score      NUMERIC(10,2) NOT NULL,
    score          NUMERIC(10,2) NOT NULL,
    calculated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT scr_score_uk UNIQUE (teacher_id, period_id, indicator_id),
    CONSTRAINT scr_score_entry_count_ck CHECK (entry_count > 0),
    CONSTRAINT scr_score_method_ck CHECK (scoring_method IN ('PER_UNIT', 'FIXED')),
    -- балл не больше максимума: главное правило расчёта закреплено и в базе
    CONSTRAINT scr_score_score_ck CHECK (score >= 0 AND score <= max_score)
);

-- сводный отчёт, рейтинг и дашборд: все баллы за период
CREATE INDEX scr_score_period_teacher_idx ON scr_score (period_id, teacher_id);

COMMENT ON TABLE scr_score IS 'Баллы по показателю у преподавателя за период. Нет записей с датой в периоде — нет строки';
COMMENT ON COLUMN scr_score.score IS 'min(total_value × coefficient, max_score) для PER_UNIT, min(entry_count × coefficient, max_score) для FIXED, округление до 0,01';
