-- Пакет scoring: начисления и итоги (разделы 6.1, 6.2, 6.4, ФР-06, 11.1).
-- Начисление создаётся только при утверждении директором и только сотрудникам:
-- доли внешних авторов остаются в ach_participant и никому не достаются.
-- Правило расчёта копируется в строку: итоги можно воспроизвести, даже если справочник потом изменится.

CREATE TABLE scr_accrual (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_id       BIGINT        NOT NULL,
    revision             INTEGER       NOT NULL,
    user_id              BIGINT        NOT NULL,
    indicator_id         BIGINT        NOT NULL,
    indicator_version_id BIGINT        NOT NULL,
    period_id            BIGINT        NOT NULL,
    base_points          NUMERIC(10,4) NOT NULL,
    coefficient          NUMERIC(10,4) NOT NULL,
    share                NUMERIC(9,6)  NOT NULL,
    points_exact         NUMERIC(14,6) NOT NULL,
    points               NUMERIC(12,2) NOT NULL,
    formula              VARCHAR(100)  NOT NULL,
    status               VARCHAR(15)   NOT NULL DEFAULT 'ACTIVE',
    calculated_by        BIGINT        NOT NULL,
    calculated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT scr_accrual_revision_uk UNIQUE (achievement_id, revision, user_id),
    CONSTRAINT scr_accrual_status_ck CHECK (status IN ('ACTIVE', 'SUPERSEDED', 'CANCELLED')),
    CONSTRAINT scr_accrual_share_ck CHECK (share > 0 AND share <= 1),
    CONSTRAINT scr_accrual_points_ck CHECK (points >= 0 AND points_exact >= 0)
);

-- два действующих начисления одному человеку по одному достижению невозможны (ТЗ 11.2)
CREATE UNIQUE INDEX scr_accrual_active_uk ON scr_accrual (achievement_id, user_id) WHERE status = 'ACTIVE';
-- пересчёт итога сотрудника за период
CREATE INDEX scr_accrual_user_period_idx ON scr_accrual (user_id, period_id);
-- срезы по показателям на дашборде
CREATE INDEX scr_accrual_period_indicator_idx ON scr_accrual (period_id, indicator_id);

COMMENT ON TABLE scr_accrual IS 'Начисления по утверждённым редакциям достижений. Прежние версии остаются со статусом SUPERSEDED';
COMMENT ON COLUMN scr_accrual.status IS 'ACTIVE — входит в итог; SUPERSEDED — заменено утверждённой новой редакцией; CANCELLED — пересмотр закончился отклонением';

CREATE TABLE scr_score (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT        NOT NULL,
    period_id            BIGINT        NOT NULL,
    indicator_id         BIGINT        NOT NULL,
    indicator_version_id BIGINT        NOT NULL,
    accrual_count        INTEGER       NOT NULL,
    total_points         NUMERIC(14,2) NOT NULL,
    max_points           NUMERIC(12,2),
    score                NUMERIC(14,2) NOT NULL,
    calculated_by        BIGINT        NOT NULL,
    calculated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT scr_score_uk UNIQUE (user_id, period_id, indicator_id),
    CONSTRAINT scr_score_count_ck CHECK (accrual_count > 0),
    CONSTRAINT scr_score_total_ck CHECK (total_points >= 0),
    -- главное правило расчёта закреплено и в базе: S = min(M, Σ), без M ограничения нет
    CONSTRAINT scr_score_score_ck CHECK (score = CASE WHEN max_points IS NULL THEN total_points ELSE LEAST(total_points, max_points) END)
);

-- дашборд и сводные отчёты: все итоги за период
CREATE INDEX scr_score_period_user_idx ON scr_score (period_id, user_id);

COMMENT ON TABLE scr_score IS 'Официальный итог сотрудника по показателю за период. Нет утверждённых начислений — нет строки';
COMMENT ON COLUMN scr_score.calculated_by IS 'Инициатор последнего пересчёта (ТЗ 6.4)';

-- Снимок официальных итогов при закрытии периода (ТЗ 4.3).
-- Если период переоткрыли и закрыли снова, появляется снимок со следующим номером.
CREATE TABLE scr_period_snapshot (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_id            BIGINT        NOT NULL,
    snapshot_no          INTEGER       NOT NULL,
    user_id              BIGINT        NOT NULL,
    indicator_id         BIGINT        NOT NULL,
    indicator_version_id BIGINT        NOT NULL,
    accrual_count        INTEGER       NOT NULL,
    score                NUMERIC(14,2) NOT NULL,
    taken_by             BIGINT        NOT NULL,
    taken_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT scr_period_snapshot_uk UNIQUE (period_id, snapshot_no, user_id, indicator_id),
    CONSTRAINT scr_period_snapshot_no_ck CHECK (snapshot_no > 0),
    CONSTRAINT scr_period_snapshot_count_ck CHECK (accrual_count > 0)
);

COMMENT ON TABLE scr_period_snapshot IS 'Итоги на момент закрытия периода. Строки только добавляются';
