-- Пакет entry: журнал достижений преподавателя и прикреплённые файлы.
-- Запись не привязана к периоду: у неё есть дата, и в отчёт за любой период
-- попадают записи, дата которых входит в этот период. Статья от 15.10 сама
-- окажется и в отчёте за октябрь, и в отчёте за семестр — вносить её дважды не нужно.
-- teacher_id и indicator_id ссылаются на таблицы других пакетов, поэтому внешних
-- ключей на них нет: существование проверяет сервис через UserService и IndicatorService.

CREATE TABLE ent_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id   BIGINT        NOT NULL,
    indicator_id BIGINT        NOT NULL,
    event_date   DATE          NOT NULL,
    value        NUMERIC(12,2) NOT NULL,
    proof_url    VARCHAR(500),
    fields       JSONB         NOT NULL DEFAULT '{}',
    comment      VARCHAR(1000),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ent_entry_value_ck CHECK (value > 0),
    CONSTRAINT ent_entry_fields_ck CHECK (jsonb_typeof(fields) = 'object')
);

-- журнал, кабинет и отчёт преподавателя: его записи за диапазон дат периода
CREATE INDEX ent_entry_teacher_date_idx ON ent_entry (teacher_id, event_date);
-- контроль сдачи, сводный отчёт, статистика по показателям: все записи за диапазон дат
CREATE INDEX ent_entry_date_indicator_idx ON ent_entry (event_date, indicator_id);

COMMENT ON TABLE ent_entry IS 'Журнал достижений преподавателя. Отчёт за период собирается по event_date';
COMMENT ON COLUMN ent_entry.event_date IS 'Когда это произошло: дата публикации, окончания курса, выступления. Определяет, в какие периоды попадает запись';
COMMENT ON COLUMN ent_entry.value IS 'Количество в единицах показателя (часы, штуки, человек). Для способа FIXED сервис пишет 1';
COMMENT ON COLUMN ent_entry.fields IS 'Значения полей формы показателя: {"key": значение}, ключи из ind_indicator.fields';

CREATE TABLE ent_attachment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id      BIGINT       NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type  VARCHAR(50)  NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    storage_key   VARCHAR(100) NOT NULL,
    uploaded_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ent_attachment_entry_fk FOREIGN KEY (entry_id) REFERENCES ent_entry (id) ON DELETE CASCADE,
    CONSTRAINT ent_attachment_storage_key_uk UNIQUE (storage_key),
    CONSTRAINT ent_attachment_content_type_ck CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    CONSTRAINT ent_attachment_size_ck CHECK (size_bytes > 0 AND size_bytes <= 10485760)
);

CREATE INDEX ent_attachment_entry_idx ON ent_attachment (entry_id);

COMMENT ON TABLE ent_attachment IS 'Подтверждающие файлы. Сам файл лежит на диске вне static/, в базе только сведения о нём';
COMMENT ON COLUMN ent_attachment.storage_key IS 'Имя файла на диске (UUID), а не имя от пользователя';

-- Отчёт за период отправлен: записи преподавателя с датой внутри этого периода менять нельзя.
-- Строку добавляет слушатель события ReportSubmitted, удаляет — слушатель ReportReturned.
-- Даты периода копируются сюда, чтобы проверка «можно ли менять запись» была одним запросом:
-- есть ли блокировка этого преподавателя, в даты которой попадает event_date.
-- Своя таблица нужна, потому что entry не может спросить report напрямую (был бы цикл).
CREATE TABLE ent_period_lock (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT      NOT NULL,
    period_id  BIGINT      NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    locked_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ent_period_lock_uk UNIQUE (teacher_id, period_id),
    CONSTRAINT ent_period_lock_dates_ck CHECK (end_date >= start_date)
);

COMMENT ON TABLE ent_period_lock IS 'Блокировка записей преподавателя за даты периода после отправки отчёта';
