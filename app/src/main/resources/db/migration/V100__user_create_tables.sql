-- Пакет user: учётные записи, оргструктура, роли и категории оценки (ТЗ 1.2, 2, ФР-01).
-- Сотрудник и учётная запись — одна таблица: id и есть стабильный идентификатор сотрудника.

CREATE TABLE usr_department (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    archived   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT usr_department_name_uk UNIQUE (name)
);

COMMENT ON TABLE usr_department IS 'Подразделения. Не удаляются, а переносятся в архив';

CREATE TABLE usr_program (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(255) NOT NULL,
    top_it     BOOLEAN      NOT NULL DEFAULT FALSE,
    archived   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT usr_program_code_uk UNIQUE (code)
);

COMMENT ON TABLE usr_program IS 'Образовательные программы';
COMMENT ON COLUMN usr_program.top_it IS 'Программа «топ-ИТ»: только её дисциплины учитываются в показателях, где нужна программа';

CREATE TABLE usr_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id          VARCHAR(50),
    login                VARCHAR(50)  NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    last_name            VARCHAR(100) NOT NULL,
    first_name           VARCHAR(100) NOT NULL,
    middle_name          VARCHAR(100),
    department_id        BIGINT,
    manager_id           BIGINT,
    position             VARCHAR(100),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT usr_user_department_fk FOREIGN KEY (department_id) REFERENCES usr_department (id),
    CONSTRAINT usr_user_manager_fk FOREIGN KEY (manager_id) REFERENCES usr_user (id),
    CONSTRAINT usr_user_login_uk UNIQUE (login),
    CONSTRAINT usr_user_external_id_uk UNIQUE (external_id),
    -- логин только в нижнем регистре: «A.Ivanova» и «a.ivanova» не станут разными людьми
    CONSTRAINT usr_user_login_ck CHECK (login ~ '^[a-z0-9.-]{3,50}$'),
    CONSTRAINT usr_user_manager_ck CHECK (manager_id <> id)
);

CREATE INDEX usr_user_department_idx ON usr_user (department_id);
CREATE INDEX usr_user_manager_idx ON usr_user (manager_id);

COMMENT ON TABLE usr_user IS 'Сотрудники и их учётные записи. Не удаляются, а деактивируются (active = false)';
COMMENT ON COLUMN usr_user.external_id IS 'Устойчивый ключ для повторного импорта (ТЗ 7.1, 7.2)';
COMMENT ON COLUMN usr_user.password_hash IS 'Хеш BCrypt, сам пароль не хранится';
COMMENT ON COLUMN usr_user.must_change_password IS 'Пароль временный: выдан при создании, сбросе или импорте';

-- Категории оценки — это не роли: ППС, АУП и РОП определяют, какие показатели применимы к человеку.
CREATE TABLE usr_user_category (
    user_id  BIGINT      NOT NULL,
    category VARCHAR(10) NOT NULL,

    CONSTRAINT usr_user_category_pk PRIMARY KEY (user_id, category),
    CONSTRAINT usr_user_category_user_fk FOREIGN KEY (user_id) REFERENCES usr_user (id),
    CONSTRAINT usr_user_category_category_ck CHECK (category IN ('PPS', 'AUP', 'ROP'))
);

COMMENT ON TABLE usr_user_category IS 'Категории оценки сотрудника, их может быть несколько';

-- Образовательные программы сотрудника. Область проверки РОП хранится отдельно, в usr_role_assignment:
-- РОП одной программы может преподавать на другой и не должен проверять её результаты.
CREATE TABLE usr_user_program (
    user_id    BIGINT NOT NULL,
    program_id BIGINT NOT NULL,

    CONSTRAINT usr_user_program_pk PRIMARY KEY (user_id, program_id),
    CONSTRAINT usr_user_program_user_fk FOREIGN KEY (user_id) REFERENCES usr_user (id),
    CONSTRAINT usr_user_program_program_fk FOREIGN KEY (program_id) REFERENCES usr_program (id)
);

CREATE INDEX usr_user_program_program_idx ON usr_user_program (program_id);

COMMENT ON TABLE usr_user_program IS 'Образовательные программы, к которым привязан сотрудник';

-- Назначение роли с областью и датами действия (ТЗ 11.1, User / RoleAssignment).
-- Закрытые строки (valid_to заполнено) остаются историей совмещения ролей.
CREATE TABLE usr_role_assignment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    role        VARCHAR(20) NOT NULL,
    program_id  BIGINT,
    valid_from  DATE        NOT NULL DEFAULT CURRENT_DATE,
    valid_to    DATE,
    assigned_by BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT usr_role_assignment_user_fk FOREIGN KEY (user_id) REFERENCES usr_user (id),
    CONSTRAINT usr_role_assignment_program_fk FOREIGN KEY (program_id) REFERENCES usr_program (id),
    CONSTRAINT usr_role_assignment_assigned_by_fk FOREIGN KEY (assigned_by) REFERENCES usr_user (id),
    CONSTRAINT usr_role_assignment_role_ck CHECK (role IN ('EMPLOYEE', 'REVIEWER', 'DIRECTOR', 'ADMIN')),
    -- у проверяющего область — его программа, у остальных ролей области нет
    CONSTRAINT usr_role_assignment_scope_ck CHECK ((role = 'REVIEWER') = (program_id IS NOT NULL)),
    CONSTRAINT usr_role_assignment_dates_ck CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- одна и та же действующая роль с той же областью у человека только одна
CREATE UNIQUE INDEX usr_role_assignment_active_uk ON usr_role_assignment (user_id, role, COALESCE(program_id, 0))
    WHERE valid_to IS NULL;
-- очередь проверки: кто РОП этой программы
CREATE INDEX usr_role_assignment_role_program_idx ON usr_role_assignment (role, program_id);

COMMENT ON TABLE usr_role_assignment IS 'Функциональные роли: у человека их может быть несколько, у РОП — по строке на программу';

-- Полномочия сверх роли, которые выдаются отдельно (ТЗ 2.2, 4.2, 7).
CREATE TABLE usr_user_permission (
    user_id    BIGINT      NOT NULL,
    permission VARCHAR(30) NOT NULL,
    granted_by BIGINT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT usr_user_permission_pk PRIMARY KEY (user_id, permission),
    CONSTRAINT usr_user_permission_user_fk FOREIGN KEY (user_id) REFERENCES usr_user (id),
    CONSTRAINT usr_user_permission_granted_by_fk FOREIGN KEY (granted_by) REFERENCES usr_user (id),
    CONSTRAINT usr_user_permission_permission_ck CHECK (permission IN ('IMPORT', 'ENTER_FOR_OTHERS', 'AUP_SELF_ENTRY'))
);

COMMENT ON TABLE usr_user_permission IS 'IMPORT — загрузка XLSX в своей области; ENTER_FOR_OTHERS — ввод за другого; AUP_SELF_ENTRY — самостоятельный ввод сотрудником АУП';

-- История переводов и смены подразделения (ФР-01). Текущая строка — та, где valid_to пусто.
CREATE TABLE usr_employment_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL,
    department_id BIGINT,
    position      VARCHAR(100),
    valid_from    DATE        NOT NULL,
    valid_to      DATE,
    changed_by    BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT usr_employment_history_user_fk FOREIGN KEY (user_id) REFERENCES usr_user (id),
    CONSTRAINT usr_employment_history_department_fk FOREIGN KEY (department_id) REFERENCES usr_department (id),
    CONSTRAINT usr_employment_history_changed_by_fk FOREIGN KEY (changed_by) REFERENCES usr_user (id),
    CONSTRAINT usr_employment_history_dates_ck CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE UNIQUE INDEX usr_employment_history_current_uk ON usr_employment_history (user_id) WHERE valid_to IS NULL;

COMMENT ON TABLE usr_employment_history IS 'Где и кем работал сотрудник. Строки только добавляются и закрываются';
