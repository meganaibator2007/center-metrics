-- Пакет user: пользователи и роли.
-- Преподаватель — это пользователь с ролью TEACHER, отдельной таблицы нет.
-- Роль хранится строкой: ролей ровно две, справочник не нужен.

CREATE TABLE usr_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login                VARCHAR(50)  NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    last_name            VARCHAR(100) NOT NULL,
    first_name           VARCHAR(100) NOT NULL,
    middle_name          VARCHAR(100),
    role                 VARCHAR(20)  NOT NULL,
    department           VARCHAR(150),
    position             VARCHAR(100),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT usr_user_login_uk UNIQUE (login),
    -- логин только в нижнем регистре: «A.Ivanova» и «a.ivanova» не станут разными людьми
    CONSTRAINT usr_user_login_ck CHECK (login ~ '^[a-z0-9.-]{3,50}$'),
    CONSTRAINT usr_user_role_ck CHECK (role IN ('TEACHER', 'ADMIN')),
    -- у преподавателя кафедра обязательна, у администратора может не быть
    CONSTRAINT usr_user_department_ck CHECK (role <> 'TEACHER' OR department IS NOT NULL)
);

COMMENT ON TABLE usr_user IS 'Пользователи: преподаватели и администраторы. Не удаляются, а блокируются (active = false)';
COMMENT ON COLUMN usr_user.password_hash IS 'Хеш BCrypt, сам пароль не хранится';
COMMENT ON COLUMN usr_user.must_change_password IS 'Пароль временный: выдан админом при создании или сбросе';
