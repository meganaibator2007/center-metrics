-- Пакет report: отчёты преподавателей и история их статусов.
-- Сам отчёт не хранит записи: содержимое отчёта за период — записи журнала с датой
-- внутри периода и баллы из scr_score. Здесь хранится только статус сдачи.
-- Строка отчёта появляется при первой отправке. Пока строки нет, отчёт считается черновиком.

CREATE TABLE rep_report (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     BIGINT        NOT NULL,
    period_id      BIGINT        NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    submitted_at   TIMESTAMPTZ,
    reviewed_at    TIMESTAMPTZ,
    reviewed_by    BIGINT,
    return_comment VARCHAR(1000),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT rep_report_uk UNIQUE (teacher_id, period_id),
    CONSTRAINT rep_report_status_ck CHECK (status IN ('DRAFT', 'SUBMITTED', 'ACCEPTED', 'RETURNED')),
    CONSTRAINT rep_report_submitted_ck CHECK (status = 'DRAFT' OR submitted_at IS NOT NULL),
    CONSTRAINT rep_report_returned_ck CHECK (status <> 'RETURNED' OR return_comment IS NOT NULL)
);

-- контроль сдачи: отчёты за период с фильтром по статусу
CREATE INDEX rep_report_period_status_idx ON rep_report (period_id, status);

COMMENT ON TABLE rep_report IS 'Отчёт преподавателя за период и его статус';
COMMENT ON COLUMN rep_report.status IS 'DRAFT — черновик, SUBMITTED — на проверке, ACCEPTED — принят, RETURNED — на доработке';
COMMENT ON COLUMN rep_report.reviewed_by IS 'Администратор, который принял или вернул отчёт (usr_user.id)';

CREATE TABLE rep_report_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT        NOT NULL,
    status     VARCHAR(20)   NOT NULL,
    comment    VARCHAR(1000),
    changed_by BIGINT        NOT NULL,
    changed_at TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT rep_report_history_report_fk FOREIGN KEY (report_id) REFERENCES rep_report (id),
    CONSTRAINT rep_report_history_status_ck CHECK (status IN ('DRAFT', 'SUBMITTED', 'ACCEPTED', 'RETURNED'))
);

CREATE INDEX rep_report_history_report_idx ON rep_report_history (report_id, changed_at);

COMMENT ON TABLE rep_report_history IS 'Кто и когда отправил, принял или вернул отчёт, с комментарием. Строки только добавляются';
